def _body() -> ExecutionBody:
    return ExecutionBody(
        stage="video",
        prompt="v7 delegation prompt",
        mode_id="first_frame",
        expected_shot_version=1,
        plan_fingerprint="a" * 64,
        compiler_wire_fingerprint="b" * 64,
    )


async def test_decision_id_is_a_client_idempotency_key_not_a_review_row(
    context,
) -> None:
    """Joint review 6-5: no HumanReviewDecision row backs a delegation.

    A delegation decision_id is generated by the client for the delegation
    action. approve_user_action must not require, look up or validate any
    HumanReviewDecision — there is deliberately no such row in this session,
    and the grant is still created.
    """

    session, actor, project, shot = context
    grants = ProductionAuthorizations(session)
    decision_id = uuid4()  # never inserted as any review row
    grant_id = await grants.approve_user_action(
        actor=actor,
        project_id=project.id,
        shot_id=shot.id,
        decision_id=decision_id,
        body=_body(),
        expires_at=datetime.now(UTC) + timedelta(minutes=10),
    )
    stored = await session.scalar(
        select(ProductionCommandAuthorization).where(
            ProductionCommandAuthorization.id == grant_id
        )
    )
    assert stored is not None
    assert stored.command_key == f"approved:{decision_id}"
    assert stored.status == "approved"
    # The same decision replayed with the same payload returns the same grant.
    assert (
        await grants.approve_user_action(
            actor=actor,
            project_id=project.id,
            shot_id=shot.id,
            decision_id=decision_id,
            body=_body(),
            expires_at=stored.expires_at.replace(tzinfo=UTC),
        )
        == grant_id
    )


async def test_expired_decision_replay_does_not_renew(context) -> None:
    """An expired grant replay returns the frozen row; it never re-approves."""

    session, actor, project, shot = context
    grants = ProductionAuthorizations(session)
    decision_id = uuid4()
    expired = datetime.now(UTC) - timedelta(minutes=1)
    # First approval with a past expiry is rejected outright.
    with pytest.raises(ConflictError, match="future timezone-aware expiry"):
        await grants.approve_user_action(
            actor=actor,
            project_id=project.id,
            shot_id=shot.id,
            decision_id=decision_id,
            body=_body(),
            expires_at=expired,
        )
    grant_id = await grants.approve_user_action(
        actor=actor,
        project_id=project.id,
        shot_id=shot.id,
        decision_id=decision_id,
        body=_body(),
        expires_at=datetime.now(UTC) + timedelta(minutes=10),
    )
    stored = await session.scalar(
        select(ProductionCommandAuthorization).where(
            ProductionCommandAuthorization.id == grant_id
        )
    )
    assert stored is not None
    # Force-expire the stored grant, then replay the same decision.
    stored.expires_at = datetime.now(UTC) - timedelta(seconds=1)
    await session.flush()
    replay = await grants.approve_user_action(
        actor=actor,
        project_id=project.id,
        shot_id=shot.id,
        decision_id=decision_id,
        body=_body(),
        expires_at=stored.expires_at.replace(tzinfo=UTC),
    )
    assert replay == grant_id
    refreshed = await session.scalar(
        select(ProductionCommandAuthorization).where(
            ProductionCommandAuthorization.id == grant_id
        )
    )
    assert refreshed is not None
    assert refreshed.expires_at.replace(tzinfo=UTC) <= datetime.now(UTC)
    # And submitting the expired grant fails closed.
    with pytest.raises(ConflictError) as exc:
        await ProductionAuthorizations(session).submit(
            actor=actor, project_id=project.id, authorization_id=grant_id
        )
    assert exc.value.details["code"] == "PRODUCTION_AUTHORIZATION_INVALID"


async def test_revoked_grant_cannot_be_submitted(context) -> None:
    session, actor, project, shot = context
    grants = ProductionAuthorizations(session)
    grant_id = await grants.approve_user_action(
        actor=actor,
        project_id=project.id,
        shot_id=shot.id,
        decision_id=uuid4(),
        body=_body(),
        expires_at=datetime.now(UTC) + timedelta(minutes=10),
    )
    await grants.revoke(
        actor=actor, project_id=project.id, authorization_id=grant_id
    )
    with pytest.raises(ConflictError) as exc:
        await ProductionAuthorizations(session).submit(
            actor=actor, project_id=project.id, authorization_id=grant_id
        )
    assert exc.value.details["code"] == "PRODUCTION_AUTHORIZATION_INVALID"


async def test_profile_version_drift_invalidates_pending_grant(context) -> None:
    session, actor, project, shot = context
    grants = ProductionAuthorizations(session)
    grant_id = await grants.approve_user_action(
        actor=actor,
        project_id=project.id,
        shot_id=shot.id,
        decision_id=uuid4(),
        body=_body(),
        expires_at=datetime.now(UTC) + timedelta(minutes=10),
    )
    profile = await session.scalar(
        select(ProjectCreativeProfile).where(
            ProjectCreativeProfile.project_id == project.id
        )
    )
    assert profile is not None
    profile.version += 1
    await session.flush()
    with pytest.raises(ConflictError) as exc:
        await ProductionAuthorizations(session).submit(
            actor=actor, project_id=project.id, authorization_id=grant_id
        )
    assert exc.value.details["code"] == "PRODUCTION_AUTHORIZATION_INVALID"
